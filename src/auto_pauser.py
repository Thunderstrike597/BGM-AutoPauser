# a small .bat under playlist-shortcuts/_bats/ that calls this app with the
# chosen playlist baked in, and a .lnk under playlist-shortcuts/ pointing at
# that .bat - so the shortcuts are easy to find, rename, or delete later
# without touching this app's own folder.
