def _setup_logging():
    try:
        handler = RotatingFileHandler(LOG_FILE, maxBytes=1_000_000, backupCount=2, encoding="utf-8")
        handler.setFormatter(logging.Formatter("%(asctime)s [%(levelname)s] %(message)s"))
        root = logging.getLogger()
        root.setLevel(logging.DEBUG if DEBUG else logging.INFO)
        root.addHandler(handler)
    except OSError:
        pass


class _StreamToLogger:
    """Stand-in for sys.stdout/sys.stderr when frozen+windowed, where
    both are None and a bare print() would raise. Routes writes to the
    log file line-by-line instead."""

    def __init__(self, level):
        self.level = level
        self._buffer = ""

    def write(self, message):
        self._buffer += message
        while "\n" in self._buffer:
            line, self._buffer = self._buffer.split("\n", 1)
            if line.strip():
                logging.log(self.level, line)

    def flush(self):
        pass

    def isatty(self):
        return False


if getattr(sys, "frozen", False):
    _setup_logging()
    sys.stdout = _StreamToLogger(logging.INFO)
    sys.stderr = _StreamToLogger(logging.ERROR)
