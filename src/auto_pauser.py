def _resolve_stream_playback_url(url, vlc_cfg):
    """VLC has no built-in understanding of a page URL like
    twitch.tv/<channel> or a YouTube watch link - handing one of those to
    VLC directly just loads its idle "no media" cone with nothing playing,
    since VLC has nothing it recognises as a media demux for an HTML page.
    yt-dlp knows how to resolve that page into the actual direct
    HLS/DASH/etc. stream URL VLC *can* play.

    Falls back to the original URL unchanged if yt-dlp doesn't recognise it
    (e.g. the user already pasted a direct .m3u8/stream URL) or resolution
    fails for any reason (offline stream, network hiccup, site changes,
    etc.) - better to let VLC attempt the raw URL than give up entirely.

    If vlc_cfg["ytdlp_cookies_from_browser"] names a browser (e.g. "chrome",
    "firefox", "edge"), yt-dlp authenticates as whatever account is logged
    into that browser - lets it request the same ad-free stream your
    subscription would get you in the browser, on sites where the
    subscriber-ad-free benefit still applies. Requires actually being
    subscribed/eligible on that channel; not something we can force.
    """
    ydl_opts = {"quiet": True, "no_warnings": True, "format": "best", "noplaylist": True}
    cookies_browser = (vlc_cfg.get("ytdlp_cookies_from_browser") or "").strip()
    if cookies_browser:
        ydl_opts["cookiesfrombrowser"] = (cookies_browser,)
    try:
        with yt_dlp.YoutubeDL(ydl_opts) as ydl:
            info = ydl.extract_info(url, download=False)
        if info and "entries" in info and info["entries"]:
            info = info["entries"][0]  # e.g. a channel page resolving to its live entry
        resolved = info.get("url") if info else None
        if resolved:
            logging.info(f"[vlc] resolved '{url}' to a direct playback URL via yt-dlp")
            return resolved
    except Exception as e:
        logging.warning(f"[vlc] yt-dlp couldn't resolve '{url}', using it as-is: {e}")
    return url


_POPOUT_WINDOW_SIZE = (480, 270)   # default pop-out size (16:9) - freely resizable afterward,
                                    # same as dragging any other window's border
_POPOUT_MARGIN = 24                # px from the screen edge


def _find_top_window_for_pid(pid, timeout=8.0, poll_interval=0.25):
    """Waits for and returns the HWND of the largest visible top-level
    window owned by the given process id - i.e. VLC's own main window,
    grabbed right after we launch it so it can be positioned/sized before
    the user even sees it appear wherever it last was. Returns None if
    nothing shows up in time (e.g. VLC failed to start)."""
    if sys.platform != "win32":
        return None

    user32 = ctypes.windll.user32
    deadline = time.time() + timeout

    def _collect_candidates():
        found = []

        @ctypes.WINFUNCTYPE(ctypes.c_bool, ctypes.c_void_p, ctypes.c_void_p)
        def _enum_proc(hwnd, _lparam):
            proc_pid = wintypes.DWORD()
            user32.GetWindowThreadProcessId(hwnd, ctypes.byref(proc_pid))
            if proc_pid.value == pid and user32.IsWindowVisible(hwnd):
                rect = wintypes.RECT()
                user32.GetWindowRect(hwnd, ctypes.byref(rect))
                area = max(0, rect.right - rect.left) * max(0, rect.bottom - rect.top)
                if area > 0:
                    found.append((area, hwnd))
            return True

        user32.EnumWindows(_enum_proc, 0)
        return found

    while time.time() < deadline:
        candidates = _collect_candidates()
        if candidates:
            candidates.sort(reverse=True)  # biggest window first - VLC's main window, not some tooltip
            return candidates[0][1]
        time.sleep(poll_interval)
    return None


def _apply_popout_geometry(pid):
    """Moves/resizes VLC's window into a small corner window - the same
    thing the user was otherwise doing by hand (drag to resize, Ctrl+H to
    hide controls) every single time. Runs in its own background thread so
    it doesn't block ensure_vlc_ready() while it waits for VLC's window to
    actually appear."""
    hwnd = _find_top_window_for_pid(pid)
    if not hwnd:
        logging.warning("[vlc] popout: never found VLC's window to resize/position")
        return

    user32 = ctypes.windll.user32
    screen_w = user32.GetSystemMetrics(0)
    screen_h = user32.GetSystemMetrics(1)
    width, height = _POPOUT_WINDOW_SIZE
    x = max(0, screen_w - width - _POPOUT_MARGIN)
    y = max(0, screen_h - height - _POPOUT_MARGIN)

    SWP_NOZORDER = 0x0004
    SWP_SHOWWINDOW = 0x0040
    user32.SetWindowPos(hwnd, None, x, y, width, height, SWP_NOZORDER | SWP_SHOWWINDOW)
    logging.info(f"[vlc] popout: positioned window at ({x}, {y}) size {width}x{height}")


def ensure_vlc_ready(controller, vlc_cfg, playlist=None, video_stream_url=None, popout=False):
    """Makes sure VLC is reachable over the HTTP interface, without ever
    touching VLC's own Preferences.

    If a working web interface is already reachable (matching password),
    VLC is left completely alone - covers the case where it's already
    running from a previous launch, or from a shortcut the user set up
    with matching --http-password/--http-port flags of their own.

    Otherwise, any running VLC is closed and a fresh one launched with
    the web interface baked into the command line
    (--extraintf http --http-password ... --http-port ...), so nothing
    needs to be configured by hand.
    """
    # Fast, single-shot check: "not reachable yet" is the normal case on a
    # cold start (VLC hasn't been launched yet at all), and this runs in the
    # background (see main()) - but keeping it quick still matters, since a
    # slow answer here delays the taskkill+relaunch decision either way.
    if controller.status(retries=0, timeout=0.75) is not None:
        logging.info("[vlc] web interface already reachable - leaving the running VLC alone")
        return

    vlc_path = resolve_vlc_path()

    try:
        subprocess.run(
            ["taskkill", "/f", "/im", "vlc.exe"],
            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
        )
    except Exception as e:
        if DEBUG:
            print(f"[vlc] taskkill failed (probably wasn't running): {e}")
    time.sleep(0.5)

    if not vlc_path:
        logging.error("[vlc] no VLC install found - can't launch it. "
                       "Set \"vlc_path\" in vlc_config.json manually.")
        return

    launch_args = [
        vlc_path,
        "--extraintf", "http",
        "--http-host", VLC_HOST,
        "--http-port", str(vlc_cfg.get("http_port", 8080)),
        "--http-password", vlc_cfg.get("http_password", ""),
    ]

    if video_stream_url:
        # Windowed and visible in the taskbar (no --qt-start-minimized) -
        # this is a live stream the user presumably wants to actually watch,
        # not background music.
        #
        # --no-qt-video-autoresize/--autoscale apply regardless of --popout:
        # VLC's default behaviour is to snap its window back to the video's
        # *native* resolution any time that resolution changes (e.g. an ad
        # break creative at a different resolution than the stream) - that's
        # what was resetting a manually-resized window back to full size.
        # Disabling autoresize + scaling the video to fit the window instead
        # keeps whatever size the window actually is.
        launch_args += ["--no-qt-video-autoresize", "--autoscale"]
        if popout:
            # --video-on-top and --qt-minimal-view are both genuine VLC
            # options - on-top pins the window above others, minimal-view is
            # the command-line equivalent of the Ctrl+H shortcut (hides the
            # menu bar/toolbar/controls). Neither one, by itself, sets an
            # initial size or position though - that's handled below via
            # _apply_popout_geometry() once the window actually exists,
            # since VLC has no command-line flag for that part.
            launch_args += ["--video-on-top", "--qt-minimal-view"]
        launch_args += [_resolve_stream_playback_url(video_stream_url, vlc_cfg)]
    else:
        launch_args += ["--qt-start-minimized"]
        if playlist:
            launch_args += ["--loop", playlist]

    try:
        proc = subprocess.Popen(launch_args)
        logging.info(
            f"[vlc] launched with web interface enabled "
            f"(playlist={playlist!r}, video_stream_url={video_stream_url!r}, popout={popout})"
        )
        if video_stream_url and popout:
            threading.Thread(target=_apply_popout_geometry, args=(proc.pid,), daemon=True).start()
    except OSError as e:
        logging.error(f"[vlc] failed to launch '{vlc_path}': {e}")


# ----------------------------------------------------------------------
# Single instance - relaunching the shortcut (e.g. with a different
# --launchPlaylist) should behave like a clean restart, not stack up a
# second tray icon and a second audio-watching loop.
# ----------------------------------------------------------------------
def ensure_single_instance():
    if sys.platform != "win32":
        return None

    kernel32 = ctypes.windll.kernel32
    mutex = kernel32.CreateMutexW(None, False, SINGLE_INSTANCE_MUTEX_NAME)
    ERROR_ALREADY_EXISTS = 183
    if ctypes.GetLastError() == ERROR_ALREADY_EXISTS:
        try:
            if getattr(sys, "frozen", False):
                # The frozen exe has a distinctive process image name, so a
                # plain taskkill-by-name (excluding our own new PID) works.
                exe_name = os.path.basename(sys.executable)
                subprocess.run(
                    ["taskkill", "/f", "/im", exe_name, "/fi", f"PID ne {os.getpid()}"],
                    stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                )
            else:
                # Running from source, the process image name is just
                # "python.exe" - too generic to taskkill by name safely (it'd
                # risk killing unrelated Python processes). Match by command
                # line instead, same approach the old run_auto_pauser.bat used.
                script_name = os.path.basename(__file__)
                ps_cmd = (
                    f"Get-CimInstance Win32_Process -Filter \"CommandLine LIKE '%{script_name}%'\" "
                    f"| Where-Object ProcessId -ne {os.getpid()} | Remove-CimInstance"
                )
                subprocess.run(
                    ["powershell", "-NoProfile", "-Command", ps_cmd],
                    stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                )
        except Exception as e:
            if DEBUG:
                print(f"[instance] failed to close previous instance: {e}")
        time.sleep(1)
    return mutex  # kept referenced for the process lifetime; not otherwise used


class VLCController:
    """Talks to VLC's built-in HTTP interface."""

    def __init__(self, host, port, password):
        self.base_url = f"http://{host}:{port}/requests"
        auth = base64.b64encode(f":{password}".encode()).decode()
        self.headers = {"Authorization": f"Basic {auth}"}

    def _get(self, path, retries=1, timeout=3.0):
        req = urllib.request.Request(self.base_url + path, headers=self.headers)
        for attempt in range(retries + 1):
            try:
                with urllib.request.urlopen(req, timeout=timeout) as resp:
                    data = resp.read()
                    if DEBUG:
                        print(f"[vlc] GET {path} -> HTTP {resp.status}")
                    return data
            except urllib.error.HTTPError as e:
                if DEBUG:
                    print(f"[vlc] HTTP error {e.code} for {path}")
                return None
            except (urllib.error.URLError, ConnectionError, TimeoutError) as e:
                if DEBUG:
                    print(f"[vlc] connection error for {path} (attempt {attempt + 1}): {e}")
        return None

    def _status_dict(self, retries=1, timeout=3.0):
        data = self._get("/status.json", retries=retries, timeout=timeout)
        if data is None:
            return None
        try:
            return json.loads(data)
        except json.JSONDecodeError:
            if DEBUG:
                print("[vlc] failed to parse status response")
            return None

    def status(self, retries=1, timeout=3.0):
        """Returns 'playing', 'paused', 'stopped', or None if VLC/web iface unreachable.
        retries/timeout are overridable - ensure_vlc_ready() uses a fast, single-shot
        check since "not reachable yet" is the common case on a cold start and
        shouldn't block the tray icon from appearing while it waits this out."""
        d = self._status_dict(retries=retries, timeout=timeout)
        return d.get("state") if d else None

    def get_volume(self):
        """Returns the current volume on VLC's 0-256(+) scale, or None if unreachable."""
        d = self._status_dict()
        if d and "volume" in d:
            return d["volume"]
        return None

    def set_volume(self, val):
        val = max(0, int(round(val)))
        self._get(f"/status.json?command=volume&val={val}")

    def pause(self):
        st = self.status()
        if DEBUG:
            print(f"[vlc] pause() called - current VLC status: {st}")
        if st == "playing":
            self._get("/status.json?command=pl_forcepause")

    def play(self):
        st = self.status()
        if DEBUG:
            print(f"[vlc] play() called - current VLC status: {st}")
        if st == "paused":
            self._get("/status.json?command=pl_forceresume")


def get_other_audio_peak():
    """Returns the max peak level (0.0-1.0) across all sessions except excluded ones."""
    peak = 0.0
    try:
        sessions = AudioUtilities.GetAllSessions()
    except Exception as e:
        if DEBUG:
            print(f"[debug] GetAllSessions failed: {e}")
        return 0.0

    for session in sessions:
        if session.Process is None:
            continue
        name = session.Process.name().lower()
        if name in EXCLUDE_PROCESS_NAMES:
            continue
        try:
            meter = session._ctl.QueryInterface(IAudioMeterInformation)
            level = meter.GetPeakValue()
            if level > peak:
                peak = level
        except Exception as e:
            if DEBUG:
                print(f"[debug] peak read failed for {name}: {e}")
            continue
    return peak


class AutoPauser:
    def __init__(self, vlc_controller: "VLCController", force_mute_mode=False):
        self.vlc = vlc_controller
        self.enabled = True

        settings = load_settings()
        self.fade_enabled = settings["fade_enabled"]

        # force_mute_mode is set when launched with --launchVideoStream: live
        # streams should always be muted rather than paused (see module
        # docstring / tray menu). self._user_mute_mode tracks the user's
        # actual saved preference underneath the forced override, so a later
        # --launchPlaylist run still sees whatever the user last set by hand,
        # never the forced value from a stream session.
        self._user_mute_mode = settings["mute_mode"]
        self.force_mute_mode = force_mute_mode
        self.mute_mode = True if force_mute_mode else self._user_mute_mode

        # Single source of truth for "what volume VLC should be at when
        # nothing is ducking/fading it" - a plain 0-100 value owned entirely
        # by this app, never read back from VLC. The previous approach
        # re-read VLC's own live volume via vlc.get_volume() every time a
        # duck began (and again on manual disable()), which is exactly what
        # caused the reported bug: that live value is whatever the fade/mute
        # logic itself most recently drove it to (including mid-fade, or
        # already-muted, values like 6% or 0), not the user's real target.
        # Now it only ever changes in response to the user - via the tray
        # volume slider (see set_desired_volume_percent) or from whatever
        # was persisted last session - and duck/undock always target this
        # value instead of asking VLC what it currently thinks the volume is.
        self.desired_volume_percent = max(0, min(100, settings.get("desired_volume_percent", 100)))

        self._stop = False
        self._sound_since = None
        self._quiet_since = None
        self._last_loud_at = None

        self._ducked = False           # True while paused/muted by us
        self._fade_state = None        # None, "out", or "in"
        self._fade_start_time = None
        self._fade_start_vol = None

    def _save_settings(self):
        mute_to_save = self._user_mute_mode if self.force_mute_mode else self.mute_mode
        save_settings({
            "fade_enabled": self.fade_enabled,
            "mute_mode": mute_to_save,
            "desired_volume_percent": self.desired_volume_percent,
        })

    def _desired_vlc_volume(self):
        """Converts the persisted 0-100 desired_volume_percent into VLC's
        native 0-256(+) volume scale."""
        return self.desired_volume_percent / 100 * VLC_FULL_VOLUME

    def get_desired_volume_percent(self):
        """What the tray volume slider should display. Deliberately never
        reads VLC's live volume - while ducked (muted, or faded/paused
        toward 0) that live value is 0 or mid-fade, not the user's real
        target."""
        return self.desired_volume_percent

    def set_desired_volume_percent(self, percent):
        """Called from the tray volume slider (and once at startup to sync
        a saved volume onto a freshly launched VLC). Always updates and
        persists the stored target. Only pushed to VLC immediately if
        playback isn't currently ducked or mid-fade - if it is, the new
        value simply becomes what gets applied next time it un-ducks,
        rather than either briefly making a muted stream audible or getting
        silently overwritten by the next fade tick."""
        self.desired_volume_percent = max(0, min(100, percent))
        self._save_settings()
        if not self._ducked and self._fade_state is None:
            self.vlc.set_volume(self._desired_vlc_volume())

    def loop(self):
        # pycaw talks to Windows' COM-based audio API, which requires each
        # thread that uses it to initialize its own COM apartment - without
        # this, calls made from this background thread fail silently and
        # get_other_audio_peak() would always report 0.
        comtypes.CoInitialize()
        try:
            while not self._stop:
                if self.enabled:
                    self._tick()
                time.sleep(CHECK_INTERVAL)
        finally:
            comtypes.CoUninitialize()

    def _fade_is_effective(self):
        return self.fade_enabled and FADE_TIME > 0

    def _begin_duck(self):
        """Start pausing/muting - either straight away, or by kicking off a fade-out."""
        if DEBUG:
            action = "muting" if self.mute_mode else "pausing"
            print(f"[auto-pauser] threshold sustained -> {action}")

        if self._fade_is_effective():
            self._fade_state = "out"
            self._fade_start_time = time.time()
            # Fades from the desired target, not from whatever VLC's live
            # volume happens to read right now - see desired_volume_percent.
            self._fade_start_vol = self._desired_vlc_volume()
        else:
            if self.mute_mode:
                self.vlc.set_volume(0)
            else:
                self.vlc.pause()

        self._ducked = True

    def _begin_undock(self):
        """Start resuming/unmuting - either straight away, or by kicking off a fade-in."""
        if DEBUG:
            action = "unmuting" if self.mute_mode else "resuming"
            print(f"[auto-pauser] quiet sustained -> {action}")

        if not self.mute_mode:
            # Playback needs to actually resume before/while the volume ramps
            # back up - otherwise there's nothing to fade in.
            self.vlc.play()

        if self._fade_is_effective():
            self._fade_state = "in"
            self._fade_start_time = time.time()
            self._fade_start_vol = 0
        elif self.mute_mode:
            self.vlc.set_volume(self._desired_vlc_volume())
        # non-mute, non-fade: pause()/play() alone already covers it.

        self._ducked = False

    def _advance_fade(self, now):
        elapsed = now - self._fade_start_time
        progress = min(1.0, elapsed / FADE_TIME)
        # Read fresh each tick (rather than snapshotted once) so a volume
        # change made mid-fade via the tray slider is picked up immediately
        # instead of being overwritten once the fade finishes.
        target = self._desired_vlc_volume()

        if self._fade_state == "out":
            vol = self._fade_start_vol * (1 - progress)
            self.vlc.set_volume(vol)
            if progress >= 1.0:
                self.vlc.set_volume(0)
                if not self.mute_mode:
                    self.vlc.pause()
                self._fade_state = None
        elif self._fade_state == "in":
            vol = target * progress
            self.vlc.set_volume(vol)
            if progress >= 1.0:
                self.vlc.set_volume(target)
                self._fade_state = None

    def _tick(self):
        peak = get_other_audio_peak()
        now = time.time()

        if DEBUG:
            self._debug_counter = getattr(self, "_debug_counter", 0) + 1
            if self._debug_counter % 10 == 0:  # roughly every ~1.5s
                bar = "#" * int(peak * 40)
                print(f"peak={peak:.3f} threshold={THRESHOLD} {bar}")

        if peak >= THRESHOLD:
            self._last_loud_at = now

        is_loud = self._last_loud_at is not None and (now - self._last_loud_at) <= LOUD_HOLD

        if self._fade_state is not None:
            self._advance_fade(now)

        if is_loud:
            self._quiet_since = None
            if self._sound_since is None:
                self._sound_since = now
            elif (
                not self._ducked
                and self._fade_state is None
                and (now - self._sound_since) >= PAUSE_AFTER
            ):
                self._begin_duck()
        else:
            self._sound_since = None
            if self._quiet_since is None:
                self._quiet_since = now
            elif (
                self._ducked
                and self._fade_state is None
                and (now - self._quiet_since) >= RESUME_AFTER
            ):
                self._begin_undock()

    def stop(self):
        self._stop = True

    def disable(self):
        """Manual 'Enabled' toggle turning OFF - stops the watcher AND
        immediately pauses/mutes VLC's current track, so switching this off
        actually silences things instead of leaving the watcher's last state
        in place until something happens to change it."""
        self.enabled = False
        self._fade_state = None
        if self.mute_mode:
            # No get_volume() read here on purpose - if this fires while
            # already auto-ducked (VLC's live volume sitting at 0, or
            # mid-fade), that read used to silently overwrite the real
            # target with whatever VLC happened to be at. desired_volume_percent
            # is untouched either way, so re-enabling always restores correctly.
            self.vlc.set_volume(0)
        else:
            self.vlc.pause()
        self._ducked = True

    def enable(self):
        """Manual 'Enabled' toggle turning back ON - resumes/unmutes VLC
        immediately and resets the watcher's timers so it starts fresh (if
        other audio is still loud, it'll naturally re-pause within
        PAUSE_AFTER seconds, same as any other time it detects noise)."""
        self.enabled = True
        self._sound_since = None
        self._quiet_since = None
        self._last_loud_at = None
        self._fade_state = None
        if self.mute_mode:
            self.vlc.set_volume(self._desired_vlc_volume())
        else:
            self.vlc.play()
        self._ducked = False


def make_icon_image(color):
    img = Image.new("RGBA", (64, 64), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    d.ellipse((8, 8, 56, 56), fill=color)
    return img


def _load_tray_icon_images():
    """Loads the app's own icon (assets/icon.ico - the same file used for
    the .exe's own icon in the .spec) for the tray, deriving a dimmed
    grayscale version for the "disabled" state from it. Falls back to a
    plain drawn dot if the asset is missing - e.g. running from source
    without an assets/ folder next to the script, or a build made before
    the asset existed - so a missing icon never crashes the app."""
    icon_path = resource_path("assets", "icon.ico")
    try:
        base = Image.open(icon_path).convert("RGBA")
    except (FileNotFoundError, OSError) as e:
        logging.warning(f"[tray] couldn't load {icon_path}, using fallback icon: {e}")
        return make_icon_image((40, 180, 99, 255)), make_icon_image((150, 150, 150, 255))

    dimmed = base.convert("L").convert("RGBA")
    dimmed.putalpha(base.split()[3])  # keep the original transparency mask
    return base, dimmed


# ----------------------------------------------------------------------
# Volume slider popup
# ----------------------------------------------------------------------
# A right-click tray menu can only ever hold text items/checkboxes - Windows'
# shell context menus have no slider control, so "a slider in the tray" is
# actually a small standalone window that appears next to where you clicked,
# same trick Windows' own volume/brightness flyouts use. It needs a Tk
# mainloop, which has to run on the main thread - so pystray's message loop
# (normally the thing blocking main()) is moved to a background thread
# instead, and the two talk to each other via a thread-safe queue rather
# than calling into Tk directly from pystray's thread.
_VOLUME_POPUP_SIZE = (220, 78)


def _get_cursor_pos():
    pt = wintypes.POINT()
    ctypes.windll.user32.GetCursorPos(ctypes.byref(pt))
    return pt.x, pt.y


def _show_volume_popup(root, pauser: "AutoPauser"):
    # Reads/writes the app's own desired_volume_percent, never VLC's live
    # volume - see AutoPauser.set_desired_volume_percent for why. This is
    # what lets the slider be dragged to set a new target while playback is
    # currently muted/paused by the auto-pauser, instead of showing (and
    # fighting with) whatever momentary 0%/mid-fade value VLC is actually at.
    percent = pauser.get_desired_volume_percent()

    popup = tk.Toplevel(root)
    popup.overrideredirect(True)      # no titlebar/border - this is a flyout, not a window
    popup.attributes("-topmost", True)
    popup.configure(bg="#2b2b2b")

    width, height = _VOLUME_POPUP_SIZE
    cursor_x, cursor_y = _get_cursor_pos()
    x = max(0, cursor_x - width // 2)
    y = max(0, cursor_y - height - 12)  # open above the click, like the menu that spawned it
    popup.geometry(f"{width}x{height}+{x}+{y}")

    tk.Label(
        popup, text="VLC Volume", fg="white", bg="#2b2b2b", font=("Segoe UI", 9)
    ).pack(pady=(8, 0))

    pct_var = tk.StringVar(value=f"{percent}%")
    last_sent_at = [0.0]
    MIN_SEND_INTERVAL = 0.05  # throttle mid-drag HTTP calls to ~20/sec

    def send_volume(pct):
        pauser.set_desired_volume_percent(pct)

    def on_change(raw_value):
        pct = int(float(raw_value))
        pct_var.set(f"{pct}%")
        now = time.time()
        if now - last_sent_at[0] >= MIN_SEND_INTERVAL:
            send_volume(pct)
            last_sent_at[0] = now

    def on_release(_event):
        send_volume(int(float(scale.get())))  # make sure the final position always lands

    row = tk.Frame(popup, bg="#2b2b2b")
    row.pack(padx=16, pady=(4, 0), fill="x")

    scale = ttk.Scale(row, from_=0, to=100, orient="horizontal", command=on_change, length=150)
    scale.set(percent)
    scale.pack(side="left", fill="x", expand=True)
    scale.bind("<ButtonRelease-1>", on_release)

    tk.Label(row, textvariable=pct_var, fg="white", bg="#2b2b2b", font=("Segoe UI", 9), width=4).pack(
        side="left", padx=(6, 0)
    )

    # Clicking elsewhere closes it, same as any other flyout
    popup.bind("<FocusOut>", lambda e: popup.destroy())
    popup.focus_force()


def _tk_ui_loop(ui_queue: "queue.Queue", pauser: AutoPauser):
    """Runs on the main thread. Owns the (hidden) Tk root and processes
    requests - opening the volume popup, shutting down - posted from the
    pystray thread via ui_queue, so pystray's own thread never touches
    Tk objects directly."""
    root = tk.Tk()
    root.withdraw()  # this root window itself is never shown - only its Toplevel popups are

    def poll_queue():
        try:
            while True:
                msg = ui_queue.get_nowait()
                if msg == "volume":
                    _show_volume_popup(root, pauser)
                elif msg == "new_shortcut":
                    _new_playlist_shortcut_flow(root)
                elif msg == "new_video_stream_shortcut":
                    _new_videostream_shortcut_flow(root)
                elif msg == "quit":
                    root.quit()
                    return
        except queue.Empty:
            pass
        root.after(100, poll_queue)

    root.after(100, poll_queue)
    root.mainloop()


def run_tray(pauser: AutoPauser, ui_queue: "queue.Queue"):
    icon_on, icon_off = _load_tray_icon_images()

    def toggle_enabled(icon, item):
        if pauser.enabled:
            pauser.disable()
        else:
            pauser.enable()
        icon.icon = icon_on if pauser.enabled else icon_off
        icon.title = "Auto-Pauser: ON" if pauser.enabled else "Auto-Pauser: OFF (paused)"

    def toggle_fade(icon, item):
        pauser.fade_enabled = not pauser.fade_enabled
        pauser._save_settings()

    def toggle_mute_mode(icon, item):
        if pauser.force_mute_mode:
            return  # greyed out in the menu already; belt-and-braces here too
        pauser.mute_mode = not pauser.mute_mode
        pauser._user_mute_mode = pauser.mute_mode
        pauser._save_settings()

    def open_volume(icon, item):
        ui_queue.put("volume")

    def new_shortcut(icon, item):
        ui_queue.put("new_shortcut")

    def new_video_stream_shortcut(icon, item):
        ui_queue.put("new_video_stream_shortcut")

    def quit_app(icon, item):
        pauser.stop()
        icon.stop()
        ui_queue.put("quit")

    def quit_app_and_vlc(icon, item):
        try:
            subprocess.run(
                ["taskkill", "/f", "/im", "vlc.exe"],
                stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
            )
        except Exception as e:
            if DEBUG:
                print(f"[quit] failed to close VLC: {e}")
        pauser.stop()
        icon.stop()
        ui_queue.put("quit")

    icon = pystray.Icon(
        "auto_pauser",
        icon_on,
        "Auto-Pauser: ON",
        menu=pystray.Menu(
            pystray.MenuItem(
                "Enabled",
                toggle_enabled,
                checked=lambda item: pauser.enabled,
            ),
            pystray.MenuItem(
                "Fade in/out",
                toggle_fade,
                checked=lambda item: pauser.fade_enabled,
            ),
            pystray.MenuItem(
                "Mute instead of pause",
                toggle_mute_mode,
                checked=lambda item: pauser.mute_mode,
                enabled=lambda item: not pauser.force_mute_mode,
            ),
            pystray.MenuItem("Volume...", open_volume),
            pystray.MenuItem("New Playlist Shortcut...", new_shortcut),
            pystray.MenuItem("Add Video Stream Shortcut...", new_video_stream_shortcut),
            pystray.Menu.SEPARATOR,
            pystray.MenuItem("Quit", quit_app),
            pystray.MenuItem("Close BGM-AutoPause && VLC", quit_app_and_vlc),
        ),
    )
    icon.run()


def parse_args():
    parser = argparse.ArgumentParser(description="BGM Auto-Pauser for VLC")
    parser.add_argument(
        "--launchPlaylist",
        dest="playlist",
        default=None,
        help="Optional folder VLC should open (looped, minimized) on startup.",
    )
    parser.add_argument(
        "--launchVideoStream",
        dest="video_stream",
        default=None,
        help="Optional stream URL VLC should open windowed (visible in the "
             "taskbar) on startup, instead of a looped/minimized playlist.",
    )
    parser.add_argument(
        "--popout",
        dest="popout",
        action="store_true",
        help="Used with --launchVideoStream: opens the stream in a "
             "sizeable, always-on-top popped-out window.",
    )
    args, _unknown = parser.parse_known_args()
    return args


def _sync_initial_volume_once_ready(pauser: "AutoPauser", controller: "VLCController", timeout=15.0):
    """Waits for VLC's web interface to come up, then applies whatever
    desired_volume_percent was loaded/persisted from last session. This is
    what makes a saved volume below 100% actually take effect on a fresh
    launch, instead of leaving VLC at whatever it started at (usually full
    volume) until the next duck/undock cycle happens to touch it. If
    playback has already been ducked by the time this runs (e.g. other
    audio was already loud at startup), set_desired_volume_percent skips
    the live push on its own, same as a slider drag would."""
    deadline = time.time() + timeout
    while time.time() < deadline:
        if controller.status(retries=0, timeout=0.75) is not None:
            pauser.set_desired_volume_percent(pauser.get_desired_volume_percent())
            return
        time.sleep(0.5)


def main():
    args = parse_args()

    # Relaunching the shortcut (possibly with a different playlist) should
    # behave like a clean restart rather than piling up tray icons.
    ensure_single_instance()

    vlc_cfg = load_vlc_config()
    controller = VLCController(VLC_HOST, vlc_cfg.get("http_port", 8080), vlc_cfg.get("http_password", ""))

    video_stream_url = (args.video_stream or "").strip() or None
    # --launchPlaylist and --launchVideoStream are mutually exclusive; a
    # stream URL (if given) takes priority since it's the more specific of
    # the two launch modes.
    playlist = None if video_stream_url else (args.playlist or vlc_cfg.get("default_playlist") or "").strip() or None
    popout = bool(args.popout) and video_stream_url is not None

    # This used to run inline here, which meant nothing appeared - no tray
    # icon, nothing - until VLC was confirmed reachable or relaunched. Now it
    # runs alongside everything else: the tray icon and pauser loop show up
    # immediately, and VLC calls the pauser loop makes in the meantime just
    # get "unreachable" (None) until this finishes, same as it already
    # handles any other time VLC isn't responding yet.
    threading.Thread(
        target=ensure_vlc_ready,
        args=(controller, vlc_cfg, playlist, video_stream_url, popout),
        daemon=True,
    ).start()

    # Launched via --launchVideoStream -> force mute-instead-of-pause for
    # this session only (see AutoPauser.__init__ / module docstring).
    pauser = AutoPauser(controller, force_mute_mode=video_stream_url is not None)
    t = threading.Thread(target=pauser.loop, daemon=True)
    t.start()

    threading.Thread(
        target=_sync_initial_volume_once_ready,
        args=(pauser, controller),
        daemon=True,
    ).start()

    # pystray's message loop and Tk's mainloop each need to own a thread of
    # their own; Tk needs the main thread, so pystray's runs in the
    # background instead, coordinating through ui_queue (see run_tray/_tk_ui_loop).
    ui_queue = queue.Queue()
    tray_thread = threading.Thread(target=run_tray, args=(pauser, ui_queue), daemon=True)
    tray_thread.start()

    _tk_ui_loop(ui_queue, pauser)
    sys.exit(0)


if __name__ == "__main__":
    main()