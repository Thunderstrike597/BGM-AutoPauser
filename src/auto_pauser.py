"""
Auto-Pauser for VLC
--------------------
Watches all Windows audio sessions EXCEPT VLC's own, and automatically
pauses (or mutes) VLC whenever any other app's audio peak crosses a
threshold. Resumes playback after a period of quiet. Optionally fades
the volume down before pausing/muting, and back up after resuming, so
it doesn't cut off mid-word.

Runs as a system tray icon so it stays out of the way. Two of the tray
menu toggles (fade, mute-instead-of-pause) are remembered across restarts
via a small settings JSON file next to this script/exe.

No manual VLC setup is required. This app talks to VLC over its built-in
HTTP interface, which it enables itself by launching VLC with
"--extraintf http --http-password <auto-generated> --http-port <port>" -
there is nothing to check or configure in VLC's Preferences. The password
is generated once and cached in vlc_config.json next to this script/exe,
alongside VLC's install path and (optionally) a default playlist folder.

If VLC is already running when this starts AND its web interface is
already reachable (e.g. it was started with matching flags previously),
it's left completely alone. Otherwise it's closed and relaunched with the
interface enabled.

Optional launch argument, meant for a shortcut's "Target"/"Arguments" field:

    "<Dir>\\Background-AutoPause.exe" --launchPlaylist "<Playlist Dir>"

When given, VLC opens looped/minimized on that folder instead of empty.
"""

